#!/usr/bin/env node
/**
 * extract-missing-abis.mjs — Extract ABIs from forge build artifacts into
 * frontend/src/lib/abi-supplement.ts, for contracts the dApp consumes but
 * does not hand-roll in frontend/src/lib/contracts.ts.
 *
 * This is the ONLY copy of this generator (2026-07-22 consolidation — a
 * stale divergent copy at scripts/extract-missing-abis.mjs was deleted;
 * root `npm run extract-abis` points here).
 *
 * Prerequisites:
 *   cd contracts && forge build
 *
 * Usage (from repo root):
 *   npm run extract-abis        # or: node frontend/scripts/extract-missing-abis.mjs
 *
 * frontend/src/lib/contracts.ts re-exports the output via
 *   export * from './abi-supplement';
 * so every entry below ships to the client surface. Keep the list to ABIs
 * with a live named import somewhere in frontend code. The 2026-07-22 prune
 * deleted 9 dead exports (~11k lines): POLAccumulator, DropV2 + FeeHook
 * (sources no longer in contracts/src/), LPFarming, NFTPool `_FULL`, Pair,
 * TokenURIReader, and the TegridyStakingAdmin / SwapFeeRouterAdmin pair —
 * admin timelock propose/execute/cancel is operated via direct contract
 * interaction, not from the dApp (see AdminPage.tsx). Grep for a named
 * import of the export before adding an entry back.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
// Repo layout: contracts/ and frontend/ are siblings at the top level.
// Script lives at frontend/scripts/, so the repo root is two levels up.
const REPO_ROOT = join(__dirname, '..', '..');
const ARTIFACT_DIR = join(REPO_ROOT, 'contracts', 'out');
const OUTPUT_FILE = join(REPO_ROOT, 'frontend', 'src', 'lib', 'abi-supplement.ts');

// Map: contract source filename -> export constant name.
// Every entry requires a live named import in frontend code (see header).
const MISSING = [
  { sol: 'TegridyTWAP.sol', name: 'TEGRIDY_TWAP_ABI' }, // hooks/useToweliPrice.ts
];

if (!existsSync(ARTIFACT_DIR)) {
  console.error(`Missing ${ARTIFACT_DIR}. Run: cd contracts && forge build`);
  process.exit(1);
}

const lines = [
  '/**',
  ' * abi-supplement.ts — Auto-generated by frontend/scripts/extract-missing-abis.mjs',
  ' *',
  ' * ABIs extracted from forge build artifacts for contracts the dApp consumes',
  ' * but does not hand-roll in contracts.ts. Re-run the script whenever one of',
  ' * the underlying Solidity contracts changes.',
  ' *',
  ' * Do NOT hand-edit — changes will be overwritten.',
  ' */',
  '',
];

let extracted = 0;
const missingArtifacts = [];

for (const { sol, name } of MISSING) {
  const contractName = sol.replace(/\.sol$/, '');
  const artifactPath = join(ARTIFACT_DIR, sol, `${contractName}.json`);
  if (!existsSync(artifactPath)) {
    missingArtifacts.push(sol);
    continue;
  }
  const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
  if (!artifact.abi || !Array.isArray(artifact.abi)) {
    console.warn(`No .abi in ${artifactPath}`);
    continue;
  }
  // Strip constructor + receive/fallback for cleaner hook generation
  const usefulAbi = artifact.abi.filter((x) => x.type !== 'constructor');
  lines.push(`export const ${name} = ${JSON.stringify(usefulAbi, null, 2)} as const;`);
  lines.push('');
  extracted++;
}

writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');

console.log(`\nWrote ${extracted}/${MISSING.length} ABIs to ${OUTPUT_FILE}`);
if (missingArtifacts.length) {
  console.warn('\nArtifacts not found for:');
  missingArtifacts.forEach((s) => console.warn(`  - ${s}`));
  console.warn('\nIf these contracts exist, they may not have been compiled by forge build.');
}

console.log('\nfrontend/src/lib/contracts.ts must keep re-exporting the output:');
console.log('  export * from \'./abi-supplement\';');
