#!/usr/bin/env node
/**
 * gen-bungalow-art.mjs — scan public/art/<bungalowId>/ and write the generated
 * per-bungalow art pools module.
 *
 * WHY GENERATED, NOT HAND-WRITTEN. The island's curator drops a folder of
 * images per community; the filenames are whatever their camera roll produced
 * (UUIDs today). Hand-maintaining 250+ literals is how a registry silently
 * drifts from the files that actually shipped — and a background pointing at a
 * missing file is a broken door, not a styling nit. This scans the real
 * directory, so the pool cannot claim art the deploy does not carry.
 *
 * Filename-agnostic on purpose: sorted lexicographically for a stable,
 * reviewable diff. Add a folder, re-run, commit the generated file.
 *
 * Usage:  node scripts/gen-bungalow-art.mjs
 */
import { readdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FRONTEND = resolve(HERE, '..');
const ART_DIR = join(FRONTEND, 'public', 'art');
const OUT = join(FRONTEND, 'src', 'lib', 'bungalowArtPools.ts');
const REGISTRY = join(FRONTEND, 'src', 'lib', 'bungalows.ts');

const IMAGE = /\.(jpe?g|png|webp|avif)$/i;

// The ids come from the registry itself, so a folder for a bungalow that does
// not exist is ignored rather than silently inventing a door.
const registrySrc = readFileSync(REGISTRY, 'utf8');
const ids = [...registrySrc.matchAll(/id: '([a-z0-9-]+)'/g)].map((m) => m[1]);
const seen = new Set();
const idsUnique = ids.filter((id) => (seen.has(id) ? false : seen.add(id)));

const pools = {};
for (const id of idsUnique) {
  const dir = join(ART_DIR, id);
  if (!existsSync(dir)) continue;
  const files = readdirSync(dir).filter((f) => IMAGE.test(f)).sort();
  if (files.length) pools[id] = files;
}

const body = Object.keys(pools).sort().map((id) => {
  const list = pools[id].map((f) => `    ${JSON.stringify(f)},`).join('\n');
  return `  ${JSON.stringify(id)}: [\n${list}\n  ],`;
}).join('\n');

const file = `/**
 * GENERATED by scripts/gen-bungalow-art.mjs — do not hand-edit.
 *
 * One entry per bungalow that has its own art folder at public/art/<id>/.
 * Filenames are listed verbatim (sorted) so the pool can never name a file the
 * deploy does not carry. Re-run the script after adding or removing art.
 */
export const BUNGALOW_ART_FILES: Record<string, readonly string[]> = {
${body}
};
`;

writeFileSync(OUT, file, 'utf8');
const total = Object.values(pools).reduce((n, a) => n + a.length, 0);
console.log(`✓ wrote ${OUT}`);
for (const id of Object.keys(pools).sort()) {
  console.log(`  ${id.padEnd(10)} ${String(pools[id].length).padStart(3)} pieces`);
}
console.log(`  ${'TOTAL'.padEnd(10)} ${String(total).padStart(3)} pieces across ${Object.keys(pools).length} bungalows`);
